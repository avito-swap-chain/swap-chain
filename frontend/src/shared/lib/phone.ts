// Телефон — единственный ключ пользователя при входе, и бэкенд проверяет его одной только
// длиной (10–32 символа). На всё, что короче, он отвечает дампом схемы валидатора вместе
// с отправленным значением — показывать такой текст в форме нельзя, поэтому формат
// проверяем до отправки, а на бэкенд уходит уже канонический номер.

/**
 * Российский номер в виде `+7XXXXXXXXXX` или `null`, если это не телефон.
 *
 * Ввод бывает в трёх видах — с `+7`, с `8` и вовсе без кода страны, — и все три означают
 * один и тот же номер. Приводим их к одному, иначе один человек заведёт себе три аккаунта:
 * для бэкенда номера различаются как строки.
 */
export function normalizePhone(raw: string): string | null {
  const digits = raw.replace(/\D/g, '')

  if (/^[78]\d{10}$/.test(digits)) return `+7${digits.slice(1)}`
  // Десять цифр без кода страны — мобильный, он начинается с девятки.
  if (/^9\d{9}$/.test(digits)) return `+7${digits}`

  return null
}
