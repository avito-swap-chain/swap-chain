import { describe, expect, it } from 'vitest'
import { normalizePhone } from './phone'

describe('normalizePhone', () => {
  it.each([
    ['+79001000001', '+79001000001'],
    ['89001000001', '+79001000001'],
    ['79001000001', '+79001000001'],
    ['9001000001', '+79001000001'],
    ['+7 (900) 100-00-01', '+79001000001'],
    ['8 900 100 00 01', '+79001000001'],
  ])('%s → %s', (raw, expected) => {
    expect(normalizePhone(raw)).toBe(expected)
  })

  it.each([
    ['', 'пустая строка'],
    ['123', 'слишком коротко'],
    ['abc', 'не цифры'],
    ['+7900', 'номер не дописан'],
    ['1234567890', 'десять цифр, но не мобильный'],
    ['+790010000012', 'лишняя цифра'],
  ])('%s отвергается: %s', (raw) => {
    expect(normalizePhone(raw)).toBeNull()
  })
})
