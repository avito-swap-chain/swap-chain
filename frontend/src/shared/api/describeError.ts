import { ApiError } from './fetcher'

/**
 * Ошибка запроса человеческим языком. Собственный `message` бэкенда сюда не идёт: он писан
 * для разработчика — на невалидном теле это дамп схемы валидатора вместе с отправленным
 * значением, и однажды такой текст уже оказался в форме входа.
 *
 * `conflict` — текст для 409. Единственный код, который в каждом действии значит своё:
 * снять вещь нельзя, потому что она уже в цепочке; отметить получение — потому что вещь
 * ещё не выехала из ПВЗ. Остальные коды одинаковы везде.
 */
export function describeError(error: unknown, conflict?: string): string {
  if (error instanceof ApiError) {
    switch (error.status) {
      case 401:
        return 'Сессия истекла — войдите заново'
      case 403:
        return 'Это действие сейчас недоступно'
      case 404:
        return 'Не найдено — возможно, данные уже изменились'
      case 409:
        return conflict ?? 'Уже неактуально — обновите страницу'
      default:
        return 'Не удалось. Попробуйте ещё раз'
    }
  }

  // `fetch` бросает `TypeError`, когда до сервера не достучались: это не ошибка ответа,
  // а его отсутствие, и человеку важно знать, что дело в связи, а не в его действиях.
  if (error instanceof TypeError) return 'Нет связи с сервером — проверьте интернет'

  // Наши собственные проверки (например, «не указано, что хочется взамен») уже написаны
  // словами для человека — их и показываем.
  if (error instanceof Error && error.message) return error.message

  return 'Не удалось. Попробуйте ещё раз'
}
