export type ItemCondition = 'new' | 'good' | 'used'

/**
 * Статус вещи в обороте обмена.
 *
 * `analyzing` — вещь опубликована, желание указано, но бэкенд ещё разбирает описание
 * и в подбор её не пускает. Это не то же самое, что `idle` («обмен не включён»): предлагать
 * там включить обмен нечего, человек уже всё заполнил, и карточка выглядела замороженной.
 *
 * `withdrawn` — обмен был включён и человек его выключил. Для подбора это то же, что `idle`,
 * но на экране разное: снятой вещи нужно подтверждение действия, а не молчание.
 */
export type ItemStatus = 'idle' | 'analyzing' | 'searching' | 'reserved' | 'withdrawn'

/** Один вариант желания — одно ребро графа, по которому ищется цепочка. */
export interface Wish {
  category: string
  description: string
}

/**
 * Что распознавание достаёт из фотографии. Названия у модели нет: она не придумывает
 * конкретный бренд, а угаданное «Redmi Note 12 Pro» вместо настоящего только вредит —
 * искать обмен будут по нему. Название пишет человек, остальное подсказывает модель.
 */
export interface RecognizedItem {
  title?: string
  category?: string
  condition?: ItemCondition
  /** Описание вещи так, как его написал бы продавец: им бэкенд и ищет обмен. */
  description?: string
  /** Адрес уже загруженного фото — чтобы при публикации не грузить его второй раз. */
  imageUrl?: string
}

/** Что пользователь заполняет в форме: вещь без служебных полей. */
export type ItemDraft = Omit<Item, 'id' | 'status'> & {
  /**
   * Сам файл фотографии — живёт только до создания вещи. `photoUrl` рядом с ним это
   * `blob:`-ссылка для предпросмотра, и бэкенду её отдавать нельзя: он принимает только
   * свои же адреса из `POST /api/v1/media` и внешние http(s).
   */
  photoFile?: File
  /**
   * Адрес фотографии в хранилище бэкенда, если она уже уехала туда ради распознавания.
   * Второй раз то же фото не загружаем.
   */
  uploadedUrl?: string
}

export interface Item {
  id: string
  title: string
  /**
   * Категория и состояние приходят не всегда: в контракте бэкенда (0.6.0) таких полей нет,
   * и по данным из API они пустые. Интерфейс это учитывает и не рисует пустую подпись —
   * додумывать состояние за пользователя нельзя, в обмене оно и есть предмет разговора.
   */
  category: string
  condition?: ItemCondition
  /**
   * Что за вещь своими словами. Бэкенд векторизует `title + description` — это единственное
   * поле, из которого подбор узнаёт о вещи хоть что-то сверх названия, поэтому оно и живёт
   * отдельно, а не собирается из категории с состоянием.
   */
  description?: string
  photoUrl?: string
  /**
   * Варианты желания: «PS5 или Xbox или беговая дорожка» — три ребра и три шанса
   * замкнуть цикл. Пустой массив = обмен на вещь не включён.
   */
  wish: Wish[]
  status: ItemStatus
}
