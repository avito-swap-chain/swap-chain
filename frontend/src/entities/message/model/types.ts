/**
 * Кто написал реплику. Роль, а не идентификатор пользователя: диалог всегда один на один
 * с соседом по кругу обмена, и на экране важно только «моё сообщение или его».
 * `system` — служебная реплика сервиса, в мессенджере Авито такие приходят от самого Авито.
 */
export type MessageAuthor = 'me' | 'them' | 'system'

export interface Message {
  id: string
  author: MessageAuthor
  text: string
  /** ISO-время отправки; в ленте показываем только часы и минуты. */
  createdAt: string
}

/**
 * Переписка по одной вещи. Ключ — вещь, а не собеседник: у Авито разговор всегда привязан
 * к объявлению, и в списке видно, о чём он. Данные собеседника и вещи лежат в самом треде,
 * потому что список диалогов рисуется без обращения к цепочкам.
 */
export interface Thread {
  itemId: string
  itemTitle: string
  itemPhotoUrl?: string
  /** Собеседник: участник, от которого вещь придёт. У служебных тредов — сам сервис. */
  peerName: string
  peerAvatarUrl?: string
  messages: Message[]
  /**
   * Есть ли непрочитанное. Ставится, когда пришла чужая реплика, снимается при открытии
   * переписки. Без этого счётчик в шапке горел бы всегда — а он должен гаснуть,
   * когда человек прочитал, как в любом мессенджере.
   */
  unread: boolean
}

/**
 * Данные, которых достаточно, чтобы завести переписку с нужной подписью в списке.
 * Без `unread`: прочитанность — состояние переписки, его ведёт api, а не вызывающий экран.
 */
export type ThreadRef = Omit<Thread, 'messages' | 'unread'>
